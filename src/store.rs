//! Saving and loading plans as JSON files in the app's data folder.
//! Each plan is one file, written atomically so a crash can't corrupt it.

use crate::model::Project;
use std::fs;
use std::io;
use std::path::{Path, PathBuf};

pub struct Store {
    dir: PathBuf,
}

/// Enough about a saved plan to list it on the start screen.
#[derive(Clone, Debug)]
pub struct Summary {
    pub id: String,
    pub name: String,
    pub modified: chrono::DateTime<chrono::Utc>,
    pub target_area: f32,
    pub units: crate::units::Units,
    pub floors: usize,
    pub shapes: usize,
}

impl Store {
    pub fn open(dir: &Path) -> io::Result<Store> {
        let dir = dir.join("plans");
        fs::create_dir_all(&dir)?;
        Ok(Store { dir })
    }

    pub fn dir(&self) -> &Path {
        self.dir.parent().unwrap_or(&self.dir)
    }

    fn path(&self, id: &str) -> PathBuf {
        // Ids are generated by us, but never trust a name that is about to
        // become a file path.
        let safe: String = id.chars().filter(char::is_ascii_alphanumeric).collect();
        self.dir.join(format!("{safe}.json"))
    }

    pub fn save(&self, p: &Project) -> io::Result<()> {
        let json = serde_json::to_vec_pretty(p).map_err(io::Error::other)?;
        let path = self.path(&p.id);
        let tmp = path.with_extension("json.tmp");
        fs::write(&tmp, json)?;
        fs::rename(&tmp, &path)
    }

    pub fn load(&self, id: &str) -> io::Result<Project> {
        let bytes = fs::read(self.path(id))?;
        serde_json::from_slice(&bytes).map_err(|e| io::Error::new(io::ErrorKind::InvalidData, e))
    }

    pub fn delete(&self, id: &str) -> io::Result<()> {
        fs::remove_file(self.path(id))
    }

    /// Saved plans, most recently edited first. Unreadable files are skipped.
    pub fn list(&self) -> Vec<Summary> {
        let Ok(rd) = fs::read_dir(&self.dir) else { return Vec::new() };
        let mut out: Vec<Summary> = rd
            .flatten()
            .filter(|e| e.path().extension().is_some_and(|x| x == "json"))
            .filter_map(|e| fs::read(e.path()).ok())
            .filter_map(|b| serde_json::from_slice::<Project>(&b).ok())
            .map(|p| Summary {
                shapes: p.floors.iter().map(|f| f.shapes.len()).sum(),
                floors: p.floors.len(),
                id: p.id,
                name: p.name,
                modified: p.modified,
                target_area: p.target_area,
                units: p.units,
            })
            .collect();
        out.sort_by(|a, b| b.modified.cmp(&a.modified));
        out
    }

    /// Import a plan from any JSON file, giving it a fresh id so it can't
    /// overwrite an existing plan.
    pub fn import(&self, path: &Path) -> io::Result<Project> {
        let bytes = fs::read(path)?;
        let mut p: Project =
            serde_json::from_slice(&bytes).map_err(|e| io::Error::new(io::ErrorKind::InvalidData, e))?;
        p.id = crate::model::fresh_id();
        self.save(&p)?;
        Ok(p)
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::geom::v2;
    use crate::model::*;
    use crate::units::Units;

    fn tmp(name: &str) -> PathBuf {
        let d = std::env::temp_dir().join(format!("drafting-table-test-{name}-{}", fresh_id()));
        fs::create_dir_all(&d).unwrap();
        d
    }

    fn sample(name: &str) -> Project {
        let mut p = Project::create(&NewPlan {
            name: name.into(),
            units: Units::Imperial,
            area: 1500.0,
            floors: 1,
            proportion: Proportion::Classic,
        });
        p.add_shape(0, Shape::boxed(Kind::Rect, v2(10.0, 10.0), v2(100.0, 100.0)));
        p
    }

    #[test]
    fn save_load_round_trip() {
        let dir = tmp("rt");
        let s = Store::open(&dir).unwrap();
        let p = sample("House");
        s.save(&p).unwrap();
        let back = s.load(&p.id).unwrap();
        assert_eq!(back.name, "House");
        assert_eq!(back.floors[0].shapes.len(), 1);
        fs::remove_dir_all(dir).ok();
    }

    #[test]
    fn list_is_newest_first_and_skips_junk() {
        let dir = tmp("list");
        let s = Store::open(&dir).unwrap();
        let mut a = sample("Old");
        a.modified = chrono::Utc::now() - chrono::Duration::days(2);
        let b = sample("New");
        s.save(&a).unwrap();
        s.save(&b).unwrap();
        fs::write(dir.join("plans").join("broken.json"), b"{ not json").unwrap();
        fs::write(dir.join("plans").join("notes.txt"), b"hello").unwrap();
        let names: Vec<_> = s.list().into_iter().map(|x| x.name).collect();
        assert_eq!(names, vec!["New", "Old"]);
        fs::remove_dir_all(dir).ok();
    }

    #[test]
    fn delete_removes_the_file() {
        let dir = tmp("del");
        let s = Store::open(&dir).unwrap();
        let p = sample("Gone");
        s.save(&p).unwrap();
        s.delete(&p.id).unwrap();
        assert!(s.load(&p.id).is_err());
        assert!(s.list().is_empty());
        fs::remove_dir_all(dir).ok();
    }

    #[test]
    fn saving_leaves_no_temp_files() {
        let dir = tmp("tmpfile");
        let s = Store::open(&dir).unwrap();
        let p = sample("Clean");
        s.save(&p).unwrap();
        s.save(&p).unwrap();
        let leftovers = fs::read_dir(dir.join("plans"))
            .unwrap()
            .flatten()
            .filter(|e| e.path().extension().is_some_and(|x| x == "tmp"))
            .count();
        assert_eq!(leftovers, 0);
        fs::remove_dir_all(dir).ok();
    }

    #[test]
    fn hostile_ids_cannot_escape_the_folder() {
        let dir = tmp("evil");
        let s = Store::open(&dir).unwrap();
        let mut p = sample("Evil");
        p.id = "../../escape".into();
        s.save(&p).unwrap();
        assert!(!dir.parent().unwrap().join("escape.json").exists());
        assert!(dir.join("plans").join("escape.json").exists());
        fs::remove_dir_all(dir).ok();
    }

    #[test]
    fn import_assigns_a_new_id() {
        let dir = tmp("imp");
        let s = Store::open(&dir).unwrap();
        let p = sample("Shared");
        s.save(&p).unwrap();
        let copy = s.import(&dir.join("plans").join(format!("{}.json", p.id))).unwrap();
        assert_ne!(copy.id, p.id);
        assert_eq!(s.list().len(), 2);
        fs::remove_dir_all(dir).ok();
    }
}
